    b.body("语言模型的 scaling law 成立，有一个常被忽略的前提：下一个词提供了近乎无限的新监督，语料越多，新组合越多。单细胞的自监督目标是重建自己，新增细胞如果与已有细胞同分布，只增加冗余，不增加信息。更硬的是维度约束：输入被基因数锁死（人类约两万），细胞类型数远小于细胞数，观测落在低维流形上。于是“更多细胞”很快退化为“同一流形的更多采样”。")
