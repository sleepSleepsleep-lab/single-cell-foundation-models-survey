    b.body("**代价**：空间数据以 targeted panel 为主，不等于所有空间平台；空间标签覆盖有限；排序仍丢幅值。它的价值在于证明“只在解离数据上训练的模型学不会空间微环境”，并展示把空间信息迁移回普通 scRNA-seq 的路径。")

    b.h3("4.1.5", "UCE：没有基因词表的通用嵌入")
