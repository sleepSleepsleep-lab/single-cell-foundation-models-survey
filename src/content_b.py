    b.h2("4.2", "B 类：三个模型的独特之处")

    b.h3("4.2.1", "scGPT：块状掩码让“敲除”变成一次前向")
    b.body("**独特设计**：注意力掩码不是 GPT 的因果掩码，也不是 BERT 的随机遮挡，而是按“CLS / 已知基因 / 待预测基因”分组的块状掩码：待预测基因只能看 CLS 与已知基因，已知基因之间互相可见。于是“预测未知”变成“用已知外推未知”，而不是“抄自己”。这解释了它为什么能做扰动预测——把被敲掉的基因设为未知即可。预训练目标是 GEP（掩码值预测）+ GEPC（细胞级对比）+ ECS（条件重构），条件 token 把批次与模态加到每个位置。")
    b.body("**代价**：每个细胞的分箱边界不同，“bin 3”在不同数据集里含义不同；1,200 个 HVG 限制了基因覆盖；zero-shot 在多项独立评测中不敌简单基线。它仍是生态最完整的模型之一（教程、微调 recipe、社区），但“基础模型”的光环需要打折。")

    b.h3("4.2.2", "TranscriptFormer：用计数分布做跨物种生成")
    b.body("**独特设计**：自回归分解为“先选基因、再定计数”：p(g_j, c_j | 前序)，输出基因 softmax 头与零截断泊松（ZTP）头。计数不是被动输入，而是进入注意力分数：score + log1p(count)，并用 tanh 软截断防止超高表达基因主导 softmax。基因身份用冻结的 ESM-2 蛋白嵌入，词表 247,388 个基因，覆盖 12 个物种、15.3 亿年进化跨度。")
    b.body("**代价**：247k 输出头很宽；自回归推理慢；随机排列意味着同一表达谱有多种写法，训练必须靠打乱让模型对排列不敏感。它是目前“生成式 + 跨物种”结合得最好的模型，也是最贵的之一。")

    b.h3("4.2.3", "scMulan：元数据也是一句话")
    b.body("**独特设计**：把细胞写成“（实体, 数值）二元组”的句子：基因词是（基因名, 1–10 档表达量），元数据词是（器官/细胞类型/性别/平台, 0），任务词是（<cell type annotation>, 0）。模型是 decoder-only、无位置编码、句内随机打乱；输出端两个头：EP 判断“下一个实体是谁”，VP 给每个候选实体一个连续数值。改句尾的任务词，就切换注释、整合、生成。")
    b.body("**代价**：10 档离散表达值损失精度；decoder-only 在长句子上成本高；预印本，1,000 万细胞在今天不算大。但它是“元数据感知 + 多任务提示”这条路线最完整的实现。")

    # ---------------------------------------------------------------- C
    b.h2("4.3", "C 类：四个模型的独特之处")

    b.h3("4.3.1", "scFoundation：把 90% 的零挡在编码器外")
    b.body("**独特设计**：非对称编解码。编码器只接收“非零且未被遮”的位置（约全长的 10%），解码器接收全部 19,266 个位置（19,264 基因 + T/S 两个深度 token）。表达值用可学习的软分箱：标量先过 Linear(1→bin_num)、LeakyReLU、再过一个线性层，softmax 成权重，与桶向量表加权求和——没有硬边界。位置嵌入 19,267×512，损失只在被遮的 30% 位置上按 MSE 计算。")
    b.body("**代价**：固定 19,264 个人类基因；MSE 被高表达基因主导；RDA 的深度缩放因子是超参。它的 scaling law 是预训练损失层面的，不能直接推下游。但“非对称稀疏”这个设计非常务实，后续不少模型沿用。")

    b.h3("4.3.2", "xTrimoGene：把稀疏性做成商业 API")
    b.body("**独特设计**：与 scFoundation 同源的非对称思路，但更早把“稀疏编码 + 读深感知”产品化，通过 BioMap API 提供扰动、药敏、注释服务，不开源。")
    b.body("**代价**：不可审计、不可本地部署；技术细节披露有限。它代表了“模型即服务”的路线，在药企场景有现实需求，但对学术复现不友好。")

    b.h3("4.3.3", "CellVQ：把一个细胞压成一个整数")
    b.body("**独特设计**：12 层 Transformer 编码 + 6 层 Performer 解码，SoftCVQ 把细胞压成 2^16 码本里的一个码字（32 维），同时输出 831 种细胞类型、377 种组织、150 种疾病等属性。位置先验不是外部 GO 矩阵，而是一张 19,266×19,266 的可训练单位阵——这张表本身就有 3.71 亿参数，占总参数的 73%。")
    b.body("**代价**：32 维瓶颈限制了表达细节；码本坍塌风险；参数效率极低。它的价值在于“细胞级离散码”这个接口——一旦细胞变成整数，就可以像词一样被检索、被语言模型消费。")

    b.h3("4.3.4", "CAPTAIN：让蛋白去“读”RNA")
    b.body("**独特设计**：交叉注意力的方向是这张图的灵魂：蛋白 token 是 query，RNA 嵌入是 key/value。每个蛋白根据自己的 token 向量，去 3,001 个基因位置里加权取信息；输出是每个蛋白的丰度与四个分位点（0.1/0.25/0.75/0.9），损失权重 0.2/0.6/0.2。RNA 侧从 scGPT 权重初始化，物种用两张独立的 gene2vec 表，训练时人和鼠必须分开组 batch。")
    b.body("**代价**：382 种蛋白的面板仍窄；物种写死为 2；蛋白数据远少于 RNA。但它是 CITE-seq 规模化预训练的第一个严肃尝试，把“补全缺失模态”变成了可训练的目标。")

    # ---------------------------------------------------------------- D
    b.h2("4.4", "D 类：四个模型的独特之处")

    b.h3("4.4.1", "CellPLM：把切片写成一串细胞")
    b.body("**独特设计**：细胞是 token，不是基因。先用稀疏矩阵乘把每个细胞的基因嵌入按表达量加权求和，得到 1,024 维细胞向量；再让 4 层 Flowformer 在同一张切片的 N 个细胞之间做线性复杂度注意力；隐空间是 16 分量高斯混合，批次标签只进解码器。空间转录组用 2D 正弦位置编码，普通 scRNA-seq 用一个共享向量顶上。")
    b.body("**代价**：基因间关系在加权求和时被抹平；推理需要切片或邻域；公开代码里位置编码被旁路（pe = 0），与论文不完全一致。它的工程价值很高——推理快、显存友好、适合“冻结嵌入 + 轻量头”。")

    b.h3("4.4.2", "State：预测 256 个细胞，而不是 1 个")
    b.body("**独特设计**：两个模块、两种数据。SE 在 1.67 亿观测细胞上学稳健表征（top 2,048 基因 + CLS + 数据集 token + 10 箱软分箱）；ST 在 1 亿多扰动细胞上学“对照 → 扰动”的变换：256 个对照细胞过 MLP 到 768 维，加上同一个扰动的嵌入，送进 8 层双向 Transformer（无位置编码、无 CLS），损失是集合之间的 MMD/能量距离。")
    b.body("**代价**：非商用许可；集合预测丢单细胞分辨率；依赖大规模扰动数据。但它是第一个把“分布级损失”做成主流的模型，也是 VCC 之后最常被引用的扰动基线。")

    b.h3("4.4.3", "tGPT：把细胞当词")
    b.body("**独特设计**：与“基因即词”相反，tGPT 把每个细胞压成一条按表达排序的基因列表，再把细胞序列当作文本做下一细胞预测。它是最早的“细胞级语言模型”，能生成细胞轨迹。")
    b.body("**代价**：单细胞分辨率下降；细胞顺序人为；后续基准表现参差。它的历史价值在于提示了一个方向：建模单元可以是细胞，而不必是基因。")

    b.h3("4.4.4", "Tahoe-x1：药物扰动矩阵上的基础模型")
    b.body("**独特设计**：建立在 Tahoe-100M 之上——50 个细胞系混在一孔、加一种药，用孔内条码与单细胞 SNP 两套正交编码拆开，产出 9,560 万细胞 × 62,710 基因、52,886 个“细胞系–药物–剂量”条件。模型把每个细胞写成 1,024 个 token，直接学扰动响应。")
    b.body("**代价**：强依赖自有数据；跨实验室泛化待验证；药物与细胞系的覆盖仍有偏。它的价值在于证明“数据生产管线本身就是模型能力的一部分”。")

    # ---------------------------------------------------------------- E
    b.h2("4.5", "E 类：四个模型的独特之处")

    b.h3("4.5.1", "Lingshu-Cell：把转录组当离散分布去噪")
    b.body("**独特设计**：掩码离散扩散。不预选 HVG，覆盖约 18,000 个基因；训练时把表达谱当作离散 token 加噪、去噪，推理时按“细胞类型/供体 × 扰动”条件生成。它不重建某一个细胞，而是学“这个条件下的表达分布”。")
    b.body("**代价**：采样慢；预印本，独立复现少；“VCC 领先”是作者口径。但它是 E 类里最彻底“换目标函数”的一个。")

    b.h3("4.5.2", "AlphaCell：在隐流形上做最优传输")
    b.body("**独特设计**：19,253 个 HGNC 基因全量输入，Mamba + Transformer 压到 32×128 的连续隐流形，再用 OT-CFM（最优传输条件流匹配）建模扰动后的状态演化；1.2B MoE 解码器保证“隐空间任意点都能翻回真实表达谱”。它把自己定位成“世界模型”：学的是状态转移算子。")
    b.body("**代价**：解码器巨大；可解释性弱；预印本。它代表了“连续时间生成”这条路线。")

    b.h3("4.5.3", "CellOS：JEPA 的双视角")
    b.body("**独特设计**：不重建输入，而是在隐空间做联合嵌入预测：一个视角是表达谱，另一个是“群体感知”视角，模型学的是两个视角表示之间的一致性。Dense-to-MoE 扩到 12B，语料 3.905 亿细胞（厂商口径）。")
    b.body("**代价**：未开源、无独立复现；MoE 推理成本高；Pearson_edist 0.619 对 0.373 的对比是厂商口径。它值得关注的是“JEPA 用于细胞”这个思路，而不是具体数字。")

    b.h3("4.5.4", "scDifformer：把扩散当后训练")
    b.body("**独特设计**：不换主干，而是在预训练之后加一个扩散后训练阶段，再做任务微调。三步范式（预训练—扩散后训练—微调）把扩散的生成能力“嫁接”到已有表征上，同时用于空间反卷积。")
    b.body("**代价**：细节披露有限；三步流程的调参复杂度高。但它是“务实改良”的代表——不追求新架构，只改训练流程。")

    # ---------------------------------------------------------------- F
    b.h2("4.6", "F 类：四个模型的独特之处")

    b.h3("4.6.1", "Cell2Sentence：细胞就是一句话")
    b.body("**独特设计**：把细胞按表达量排序，取前若干基因的**名字**拼成自然语言句子，直接微调 GPT-2。不需要新词表、不需要改架构，复用 LLM 的语义先验。可用于细胞生成、补全、注释。")
    b.body("**代价**：表达幅值丢失；基因名分词不稳定；长序列。它的价值是“零改造”的思路——任何 LLM 都能尝试。")

    b.h3("4.6.2", "GenePT：不训练模型，只问 ChatGPT")
    b.body("**独特设计**：用 ChatGPT 给每个基因的描述做文本嵌入，细胞表示就是基因嵌入按表达的加权和。没有 GPU、没有预训练，却在不少任务上“简单但难打败”。")
    b.body("**代价**：完全不学表达感知的表示；文本质量决定上限；无法做生成。它是对“必须训练大模型”这个假设的最有力反例。")

    b.h3("4.6.3", "LangCell：细胞与文本的对比对齐")
    b.body("**独特设计**：细胞-文本配对预训练，用自然语言描述细胞身份，做零样本/文本引导的注释。")
    b.body("**代价**：配对数据稀缺；语义对齐不等于定量理解。它属于 F 类里“对齐派”，与 CellWhisperer 同路。")

    b.h3("4.6.4", "CellWhisperer：给 UMAP 上色的一句话")
    b.body("**独特设计**：CLIP 式双塔：表达谱走 Geneformer（全程冻结），文本走 BioBERT，各接一个适配器压到 2,048 维，用 108 万对“转录组–文本”做对比学习。文本不是原始元数据，而是用 GPT-4 把表格重写成有生物学信息量的句子。检索就是一次点积，所以“用一个词给整张 UMAP 上色”在数学上是余弦相似度。")
    b.body("**代价**：caption 由模型生成，元数据缺失时会“补全”，标签噪声从第一天进入监督；检索不是生成；基因表达塔被冻结，无法为对齐调整。但它是“自然语言接口”最落地的实现，零样本检索 AUROC 0.927。")

