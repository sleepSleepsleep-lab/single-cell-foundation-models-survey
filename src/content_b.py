    b.h2("4.1", "A 类：八个模型的独特之处")

    b.h3("4.1.1", "scBERT：第一个把 BERT 搬到转录组")
    b.body("**独特设计**：用 gene2vec 的基因身份向量替代 BERT 的位置编码。这个替换很聪明——基因没有顺序，但基因之间有功能相似性，gene2vec 恰好提供了“相对位置”。序列长达 16,907 个位置，标准注意力装不下，于是用 Performer 的线性注意力（FAVOR+）把 O(N²) 降到 O(N)。预训练只遮非零表达（15%），避免模型把“零”学成默认答案。")
    b.body("**代价**：200 维的模型宽度是被 gene2vec 的维度定死的，容量偏小；词表固定为 16,906 个基因；Performer 的核近似有误差。后续评测显示，PBMC 上 L1 逻辑回归在 accuracy 与 macro-F1 上都胜过它，去掉预训练也没有统计差异。它的历史意义大于实用价值。")

    b.h3("4.1.2", "Geneformer：用“排行榜”代替表达值")
    b.body("**独特设计**：rank value encoding。先把每个细胞的总计数拉到 10,000，再逐基因除以它在 3,000 万细胞里的中位表达，最后只取非零基因、按数值降序排成 2,048 个 token。除中位表达这一步是关键：它把 ubiquitously 高表达的管家基因压到后面，把“平时不表达、一旦表达就决定身份”的转录因子顶到前面。模型只有 6 层、4 头、256 维、约 1,000 万参数——刻意做小，以匹配数据规模。")
    b.body("**代价**：绝对幅值完全丢失，两个排序相同的细胞得到同一条序列；dropout 掉一个计数会让整条排名平移；2,048 截断会切掉 7% 细胞的尾部。它的 in silico 扰动（删基因、改秩次）是相关性推断，不是因果。但在数据稀缺的网络生物学任务上，它是第一个证明“迁移学习有效”的模型。")

    b.h3("4.1.3", "GeneCompass：把四类生物先验拼进输入")
    b.body("**独特设计**：五路拼接再投影，而不是逐元素相加。每个基因位置把基因 ID（768 维）、表达值（1 维）、GRN 嵌入（768）、启动子嵌入（768）、基因家族嵌入（768）、共表达嵌入（768）沿特征维拼成 3,841 维，再投影回 768。拼接保留了“这一维来自哪一路”的身份，代价是首层参数从 768² 涨到 3,841×768。跨物种用同源索引：鼠基因先映射到人同源 ID，再查同一套知识表；物种 token 放在第 0 位。")
