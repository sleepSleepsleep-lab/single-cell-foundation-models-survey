    b.body("**代价**：单物种（人类）；800M 参数与下游增益之间没有解耦证据；许可标注为“Other”，商用需逐一确认。它的意义更多在工程侧——证明国产算力可以训练亿级参数的单细胞模型。")

    b.h3("4.1.7", "scPRINT：把基因网络当作第一目标")
    b.body("**独特设计**：输出端不是重建值，而是每个基因的 ZINB 参数（μ、θ、π）；训练不是遮 token，而是用泊松下采样 + dropout 重新模拟一次测序，让模型学“从稀疏还原稠密”。基因 token 由三路相加：ESM-2 蛋白嵌入、表达量 MLP、基因组位置正弦编码。注意力矩阵直接当作基因网络输出，并用公开 GRN 基准评测。")
    b.body("**代价**：2,200 个基因的上下文上限；80B token 的训练成本不低；注意力是否等于调控仍有争议。但它是少数把“可解释输出”当成主任务而不是副产品的模型。")

    b.h3("4.1.8", "RegFormer：GRN 引导的基因排序 + Mamba")
    b.body("**独特设计**：用基因调控层级决定基因顺序，把“谁调控谁”变成序列先验；双嵌入（表达值 + 基因 token）后接 Mamba 状态空间，把长基因序列的复杂度降到线性。2,500 万人类细胞、45 种组织，任务覆盖聚类、整合、注释、GRN 重建、扰动与药敏。")
    b.body("**代价**：人类单物种；GRN 先验的质量决定上限；2026 年新刊，独立复现还少，“全面优于”是作者口径。它代表了“先验结构化”这条路线在 2026 年的最新形态。")

